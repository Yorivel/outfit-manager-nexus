"""Outfit Manager's languages: the mod's lang\\en.txt -> plugin/src/lang_en.inc (the English built into the plugin), and a
check of every other lang\\<code>.txt against it (keys English doesn't have, {placeholders} that differ, lines missing).
lang_gen.py            (run before building the plugin when en.txt changed)"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
LANG = os.path.join(ROOT, 'mod', 'Outfit Manager', 'lang')
INC = os.path.join(ROOT, 'plugin', 'src', 'lang_en.inc')
PLURAL = ('.zero', '.one', '.two', '.few', '.many', '.other')


def read(path):
    out = {}
    for n, line in enumerate(open(path, encoding='utf-8-sig'), 1):
        l = line.strip()
        if not l or l.startswith('#'):
            continue
        if '=' not in l:
            print(f'{os.path.basename(path)}:{n}: no "=": {l}')
            continue
        k, v = l.split('=', 1)
        out[k.strip()] = v.strip()
    return out


def holes(text): return sorted(set(re.findall(r'\{(\w+)\}', text)) - {'sp'})


def base(key):
    for p in PLURAL:
        if key.endswith(p):
            return key[:-len(p)]
    return key


def c_string(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


if __name__ == '__main__':
    en = read(os.path.join(LANG, 'en.txt'))
    with open(INC, 'w', encoding='utf-8', newline='\n') as f:
        f.write('// Generated by tools/lang_gen.py from the mod\'s lang\\en.txt: do not edit.\n')
        for k, v in en.items():
            f.write(f'{{{c_string(k)}, {c_string(v)}}},\n')
    print(f'en: {len(en)} lines -> {os.path.relpath(INC, ROOT)}')
    en_bases = {base(k): k for k in en}
    for name in sorted(os.listdir(LANG)):
        if not name.endswith('.txt') or name == 'en.txt' or name.endswith('.custom.txt'):
            continue
        tr = read(os.path.join(LANG, name))
        problems = []
        for k, v in tr.items():
            ref = en.get(k) or (en.get(base(k) + '.other') if base(k) in en_bases else None)
            if ref is None:
                problems.append(f'  unknown key {k}')
            elif (not set(holes(v)) <= set(holes(ref))) if base(k) != k else holes(v) != holes(ref):
                # (a plural form may leave {n} out: Arabic's "one piece", "two pieces")
                problems.append(f'  {k}: {{{",".join(holes(v))}}} vs English {{{",".join(holes(ref))}}}')
        missing = [k for k in en if k not in tr and not (base(k) != k and any(x.startswith(base(k) + '.') for x in tr))]
        print(f'{name}: {len(tr)} lines, {len(missing)} missing' + (': ' + ', '.join(missing[:8]) if missing else ''))
        for p in problems:
            print(p)
